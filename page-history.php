<script>
window.addEventListener('load', function() {
  if (typeof gsap === 'undefined' || typeof ScrollTrigger === 'undefined') {
    return;
  }

  gsap.registerPlugin(ScrollTrigger);

  const panelsWrapper = document.querySelector('.p-history__wrapper');
  const panelBox = document.querySelector('.p-history__box');
  if (!panelsWrapper || !panelBox) {
    return;
  }

  const END_PADDING = 300;
  const isDesktop = () => window.matchMedia('(min-width: 768px)').matches;

  const getHorizontalScroll = () => {
    const viewportWidth = panelsWrapper.clientWidth;
    const contentWidth = panelBox.scrollWidth;
    return Math.max(contentWidth - viewportWidth + END_PADDING, 0);
  };

  if (getHorizontalScroll() <= 0) {
    return;
  }

  const scrollConfig = {
    trigger: panelsWrapper,
    pin: true,
    scrub: 1,
    start: isDesktop() ? 'top+=20% 25%' : 'top 25%',
    end: () => '+=' + getHorizontalScroll(),
    invalidateOnRefresh: true,
    anticipatePin: 1,
  };

  gsap.to(panelBox, {
    x: () => -getHorizontalScroll(),
    ease: 'none',
    scrollTrigger: scrollConfig,
  });

  const truck = document.querySelector('.p-history__icon');
  if (truck) {
    gsap.to(truck, {
      x: () => {
        const trackWidth = panelsWrapper.clientWidth;
        const truckWidth = truck.offsetWidth;
        const startOffset = window.matchMedia('(min-width: 768px)').matches ? 20 : 5;
        return Math.max(trackWidth - truckWidth - startOffset, 0);
      },
      ease: 'none',
      scrollTrigger: {
        trigger: panelsWrapper,
        scrub: 1,
        start: scrollConfig.start,
        end: scrollConfig.end,
        invalidateOnRefresh: true,
      },
    });
  }

  ScrollTrigger.refresh();
  window.addEventListener('resize', () => ScrollTrigger.refresh());
});
</script>
